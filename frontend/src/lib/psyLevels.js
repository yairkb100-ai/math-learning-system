// שלוש הרמות של פריט במאגר קרני, במקום אחד כדי ששלושת המסכים שמציגים אותן
// (הבית, התרגול, הדוח) יקראו להן באותם שמות ובאותם גוונים.
//
// הרמה אינה "כמה קשה" — זה `difficulty`. הרמה היא **היכן השאלה עומדת מול מבחן
// קרני האמיתי**: מתחת לרף, על הרף, מעל הרף. שאלת בית-ספר עם מספרים מכוערים
// היא קשה ועדיין "רמת מתחילים", כי במבחן האמיתי נבחנת הטכניקה ולא החישוב.
//
// הגוונים מגיעים ממחלקות ריבוע-הכיתה שכבר קיימות ב-index.css (--lv/--lv-bg),
// באותה שיטה שבה `psy-sim-tag` צובע את תווית "רמה מתקדמת" בכרטיס הסימולציה.
export const PSY_LEVELS = ['beginner', 'standard', 'advanced']

export const LEVEL_META = {
  beginner: {
    label: 'רמת מתחילים',
    short: 'מתחילים',
    ramp: 'grade-5',
    blurb: 'שאלות בסיס — נפתרות ישר, בלי טכניקה פסיכוטכנית. נקודת פתיחה טובה.',
  },
  standard: {
    label: 'רמת יעד',
    short: 'רמת יעד',
    ramp: 'grade-7',
    blurb: 'רמה שמותאמת למטרות ההכנה — טכניקה אחת ומלכודת אחת.',
  },
  advanced: {
    label: 'רמה מתקדמת',
    short: 'מתקדם',
    ramp: 'grade-hs',
    blurb: 'מעל רמת המבחן — שתי טכניקות משורשרות או חוקיות מוסתרת.',
  },
}

// כרטיס נושא מקבל level_counts מהשרת. מפתח חסר = אין שאלות ברמה הזו, ולכן
// היא לא מוצגת בכלל — "0 מתקדמות" הוא רעש, לא מידע.
export function levelBreakdown(counts) {
  if (!counts) return []
  return PSY_LEVELS.filter((k) => counts[k] > 0).map((k) => ({
    key: k,
    n: counts[k],
    ...LEVEL_META[k],
  }))
}
