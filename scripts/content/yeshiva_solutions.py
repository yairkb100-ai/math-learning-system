def attach(table, level, items):
    """Zip (q, a) items with their solutions, cross-checking the numbers."""
    sols = table[level]
    assert len(sols) == len(items), (level, len(sols), len(items))
    out = []
    for (q, a), (vals, steps) in zip(items, sols):
        have = _nums(a)
        for v in vals:
            assert str(v) in have, "solution value %s not in answer %r for %r" % (v, a, q[:50])
        out.append((q, a, steps))
    return out
