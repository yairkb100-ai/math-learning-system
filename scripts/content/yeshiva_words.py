"""Sub-topics 6-9 of "הכנה לישיבות": age, buying/selling, percent and motion
word problems.  Hand-written stories; every multi-condition story is verified by
brute-force search (exactly one admissible solution) before its answer is printed.
"""

from itertools import product
from fractions import Fraction as Fr

LEVEL_COUNTS = (10, 15, 15)


def P(pct):
    return r"$%s\%%$" % pct


def one(cands, pred):
    sols = [c for c in cands if pred(*c)]
    assert len(sols) == 1, sols
    return sols[0]


def R(*r):
    return range(*r)


def hm(minutes):
    h, m = divmod(int(minutes), 60)
    hs = {0: "", 1: "שעה", 2: "שעתיים"}.get(h, "%d שעות" % h)
    if m == 0:
        return hs
    ms = "%d דקות" % m
    return ms if not hs else hs + " ו-" + ms


def _levels(l1, l2, l3):
    assert (len(l1), len(l2), len(l3)) == LEVEL_COUNTS, (len(l1), len(l2), len(l3))
    return {1: l1, 2: l2, 3: l3}


