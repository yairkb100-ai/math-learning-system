"""Explanations and tips for "הכנה לישיבות" — one guide per sub-topic plus a short
guide per part (חשבון / בעיות מילוליות / משוואות).

A guide is a list of blocks:
    ("h", text)                       section heading
    ("p", text)                       paragraph
    ("ul", [text, ...])               bullets
    ("ol", [text, ...])               numbered list
    ("table", [header], [[row], ...]) table (cells may hold $math$)
    ("ex", question, [steps], answer, table|None) worked example
Text may contain **bold** and $math$.  Keep math to plain KaTeX that both the app
(KaTeX) and the PDF pipeline (gen_chapter_assets.macros) understand: \\frac,
\\times, \\div, \\cdot, ^{}, parentheses and bars.  No \\text{}, no \\ldots.

The worked examples use their own numbers (not the worksheet's), and every number
in them is re-computed by ``check_examples()`` below.
"""

