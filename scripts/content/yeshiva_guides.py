def check_examples():
    """Re-compute every number quoted in a worked example."""
    f = Fr
    assert 30 - 4 * (3 + 2) / 5 == 26
    assert f(3, 4) + f(5, 6) == f(19, 12) and f(19, 12) == 1 + f(7, 12)
    assert f(5, 3) / f(5, 6) == 2 and 1 + f(2, 3) == f(5, 3)
    assert (f("7.5") - f("3.5")) * f("0.25") + f("2.4") / f("0.4") == 7
    assert 3 * (30 - (4 + 8) / 2) == 72
    assert abs(3 - 8) - abs(-2) * 3 == -1
    assert all(abs(x + 1) == 4 for x in (3, -5))
    # ages: son x, father 3x; 8 years ago father = 5 * son
    sols = [x for x in range(1, 100) if 3 * x - 8 == 5 * (x - 8) and x > 8]
    assert sols == [16] and 3 * 16 == 48 and 40 == 5 * 8
    # oranges
    sols = [x for x in range(1, 100) if 20 * (x + 3) - 25 * x == 30]
    assert sols == [6] and 25 * 6 == 150 and 20 * 9 == 180
    # percent
    assert f(240) / f("0.8") == 300 and f("0.2") * 300 == 60
    # motion: motorcycle head start 1h
    sols = [t for t in range(1, 50) if 40 * (t + 1) == 60 * t]
    assert sols == [2] and 8 + 1 + 2 == 11 and 40 * 3 == 120 == 60 * 2
    # equations
    assert [x for x in range(-50, 50) if 3 * (x - 2) - 2 * (x + 1) == 7] == [15]
    assert 3 * 13 - 2 * 16 == 7
    assert [x for x in range(-50, 50) if f(x + 1, 2) == 5] == [9]
    # systems
    assert [(x, y) for x in range(-20, 20) for y in range(-20, 20) if 2 * x + 3 * y == 14 and x - y == 2] == [(4, 2)]
    assert [(x, y) for x in range(-20, 20) for y in range(-20, 20) if 3 * x + 2 * y == 22 and 2 * x - 2 * y == 8] == [(6, 2)]
    # quoted tips
    assert 24 / 4 * 2 == 12 and 10 - 3 + 2 == 9 and 10 - (3 + 2) == 5 and (-3) ** 2 == 9
    assert f(1, 2) + f(1, 3) == f(5, 6) and f(5, 2) * 3 == f(15, 2) and 6 / f(3, 4) == 8 and f(3, 5) * 20 == 12
    assert f("3.5") + f("2.75") == f("6.25") and f("0.3") * f("0.4") == f("0.12") and f("4.5") / f("0.15") == 30
    assert f("0.3") * f("0.2") == f("0.06") and f("4.8") * f("0.5") == f("2.4")
    assert f("1.1") * f("1.2") == f("1.32") and f("1.1") * f("0.9") == f("0.99") and f(15, 60) == f(1, 4)
    assert f(24) / f("0.3") == 80 and 3 * (4 + 5) == 27 and (60 + 60) / (1 + 2) == 40 and (60 + 30) / 2 == 45
