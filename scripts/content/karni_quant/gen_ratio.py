# ---------------------------------------------------------------- formatting
def n(x):
    x = F(x)
    if x.denominator == 1:
        v = x.numerator
        return f"{v:,}" if abs(v) >= 1000 else str(v)
    t = x.denominator
    while t % 2 == 0:
        t //= 2
    while t % 5 == 0:
        t //= 5
    assert t == 1, f"non terminating {x}"
    return f"{float(x):.10f}".rstrip("0").rstrip(".")


def un(unit):
    return lambda v: f"{n(v)} {unit}"


def pct(v):
    return f"{n(v)}%"


def rf(v):
    """plain ratio option for a simplified Fraction"""
    v = F(v)
    return f"{v.numerator} : {v.denominator}"


def rm(v):
    """math ratio for stems / solutions"""
    v = F(v)
    return f"${v.numerator}:{v.denominator}$"


def R(*parts):
    return "$" + ":".join(str(p) for p in parts) + "$"


def fix_nums(t):
    """thousands separators: plain text 1,200 ; inside $...$ 1{,}200 (a bare comma would add a space)"""
    parts = t.split("$")
    for i, seg in enumerate(parts):
        seg = seg.replace("{,}", "")
        seg = __import__("re").sub(r"(?<![\d.,])(\d{1,3}(?:,\d{3})+|\d{4,})(?![\d])",
                                   lambda m: "{:,}".format(int(m.group(1).replace(",", ""))), seg)
        if i % 2 == 1:
            seg = seg.replace(",", "{,}")
        parts[i] = seg
    return "$".join(parts)


def lead(s):
    return RLM + s if s[:1].isdigit() else s


def tri(t):
    g = gcd(gcd(t[0], t[1]), t[2])
    return tuple(v // g for v in t)


def isint(x):
    return F(x).denominator == 1


# ---------------------------------------------------------------- item makers
def add(sub, qt, diff, secs, stem, ans, wrongs, fmt, expl, sol, tags):
    vals = [F(ans)] + [F(w) for w in wrongs]
    assert len(vals) == 4 and len(set(vals)) == 4, (stem, vals)
    strs = [fmt(v) for v in vals]
    assert len(set(strs)) == 4, (stem, strs)
    order = sorted(range(4), key=lambda i: vals[i])
    options = [strs[i] for i in order]
    ci = order.index(0)
    assert options[ci] == fmt(F(ans))
    for i, v in enumerate(vals):
        assert (v == F(ans)) == (i == 0)
    _push(sub, qt, diff, secs, stem, options, ci, expl, sol, tags)


def addr(sub, qt, diff, secs, stem, ans, wrongs, expl, sol, tags):
    """ratio options (Fractions), all in simplest form 'a : b'"""
    add(sub, qt, diff, secs, stem, ans, wrongs, rf, expl, sol, tags)


def add3(sub, qt, diff, secs, stem, ans, wrongs, expl, sol, tags):
    """three-term ratio options"""
    vals = [tri(ans)] + [tri(w) for w in wrongs]
    assert len(set(vals)) == 4
    order = sorted(range(4), key=lambda i: vals[i])
    options = [" : ".join(map(str, vals[i])) for i in order]
    _push(sub, qt, diff, secs, stem, options, order.index(0), expl, sol, tags)


def addc(sub, qt, diff, secs, stem, labels, ci, expl, sol, tags):
    assert len(set(labels)) == 4
    _push(sub, qt, diff, secs, stem, list(labels), ci, expl, sol, tags)


def _push(sub, qt, diff, secs, stem, options, ci, expl, sol, tags):
    assert 25 <= secs <= 60 and expl != sol
    for o in options:
        assert "$" not in o and "*" not in o
    ITEMS.append({
        "ref": "", "domain": "quantitative", "qtype": qt, "topic": TOPIC,
        "subtopic": sub, "stem": fix_nums(stem), "options": options, "correct_index": ci,
        "difficulty": diff, "target_seconds": secs, "explanation": lead(fix_nums(expl)),
        "solution": lead(fix_nums(sol)), "tags": tags,
    })


def share(total, parts, i):
    return F(total) * parts[i] / sum(parts)


