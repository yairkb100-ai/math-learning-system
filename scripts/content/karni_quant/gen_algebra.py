# ---------------------------------------------------------------- helpers
def lin(lhs, rhs):
    """Solve the linear equation lhs = rhs for x, exactly."""
    L, R = sp.sympify(lhs, rational=True), sp.sympify(rhs, rational=True)
    syms = list((L - R).free_symbols)
    assert len(syms) == 1, (lhs, rhs)
    sol = sp.solve(sp.Eq(L, R), syms[0])
    assert len(sol) == 1, (lhs, rhs, sol)
    return F(int(sol[0].p), int(sol[0].q))


def txt(v):
    """number -> plain text, ascii hyphen (use inside $...$)."""
    v = F(v)
    if v.denominator == 1:
        return str(v.numerator)
    d = v * 100
    assert d.denominator == 1, f"unclean decimal {v}"
    s = f"{float(v):.2f}".rstrip("0").rstrip(".")
    return s


def opt(v):
    """number -> option text with a real minus sign."""
    return txt(v).replace("-", MINUS)


def M(s):
    s = s.replace("@", CDOT)
    s = re.sub(r"FR<(.*?)\|(.*?)>", lambda m: FRAC + "{" + m.group(1) + "}{" + m.group(2) + "}", s)
    return "$" + s + "$"


def v(val):
    """number inside Hebrew prose: negatives wrapped in math."""
    val = F(val)
    return M(txt(val)) if val < 0 else txt(val)


def parse_disp(s):
    s = s.replace(MINUS, "-")
    s = re.sub(r"(\d)([a-z])", r"\1*\2", s)
    return sp.sympify(s, rational=True)


def add(ref_sub, qtype, stem, options, ci, diff, secs, expl, sol, tags):
    assert len(options) == 4 and len(set(options)) == 4, options
    assert 0 <= ci <= 3
    assert expl != sol
    for o in options:
        assert "$" not in o and "*" not in o
    ITEMS.append({
        "ref": "",
        "domain": "quantitative",
        "qtype": qtype,
        "topic": "אלגברה",
        "subtopic": ref_sub,
        "stem": stem,
        "options": options,
        "correct_index": ci,
        "difficulty": diff,
        "target_seconds": secs,
        "explanation": expl,
        "solution": sol,
        "tags": tags,
    })


def num(sub, stem, ans, wrongs, diff, secs, expl, sol, tags, qtype="algebra", unit=""):
    """Numeric options, ascending. wrongs: list of 3 values."""
    ans = F(ans)
    wrongs = [F(w) for w in wrongs]
    assert len(wrongs) == 3
    allv = [ans] + wrongs
    assert len(set(allv)) == 4, allv
    assert all(w != ans for w in wrongs)
    allv.sort()
    options = [opt(a) + (" " + unit if unit else "") for a in allv]
    ci = allv.index(ans)
    add(sub, qtype, stem, options, ci, diff, secs, expl, sol, tags)


def expr(sub, stem, truth, options, ci, diff, secs, expl, sol, tags, qtype="algebra"):
    """Expression options (display strings); verified symbolically."""
    t = sp.sympify(truth, rational=True)
    for i, o in enumerate(options):
        # bidi safety: a letter must open the string (or follow its first number)
        assert re.match(r"^[\d.]*[a-z]", o), o
        same = sp.simplify(parse_disp(o) - t) == 0
        assert same == (i == ci), (o, truth, i, ci)
    add(sub, qtype, stem, options, ci, diff, secs, expl, sol, tags)


def eqopt(sub, stem, expected, options, ci, diff, secs, expl, sol, tags, qtype="word-problem"):
    """Equation options; only the keyed one has the expected root."""
    for i, o in enumerate(options):
        assert re.match(r"^[\d.]*[a-z]", o), o
        l, r = o.replace(MINUS, "-").split("=")
        l = re.sub(r"(\d)([a-z])", r"\1*\2", l)
        r = re.sub(r"(\d)([a-z])", r"\1*\2", r)
        root = lin(l, r) if "x" in (l + r) else None
        assert (root == F(expected)) == (i == ci), (o, root)
    add(sub, qtype, stem, options, ci, diff, secs, expl, sol, tags)


