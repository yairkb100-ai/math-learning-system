ITEMS = []


def n(x, comma=True):
    x = F(x)
    if x.denominator == 1:
        v = int(x)
        return f"{v:,}" if comma else str(v)
    assert (x * 100).denominator == 1, x
    s = f"{float(x):.2f}".rstrip("0").rstrip(".")
    return s


def nm(x):  # number inside math: no thousands comma
    return n(x, comma=False)


BS = chr(92)


def M(s):
    return "$" + s.replace("@T", BS + "times").replace("@frac", BS + "frac") + "$"


def pc(v):
    return n(v) + "%"


def sh(v):
    return n(v) + " ש״ח"


def U(word):
    return lambda v: f"{n(v)} {word}"


def add(sub, stem, ans, wrongs, fmt, d, secs, expl, sol, tags, qtype="word-problem"):
    ans = F(ans)
    wrongs = [F(w) for w in wrongs]
    assert len(wrongs) == 3
    vals = [ans] + wrongs
    assert len(set(vals)) == 4, (stem, vals)
    for w in wrongs:
        assert w != ans
    vs = sorted(vals)
    opts = [fmt(v) for v in vs]
    assert len(set(opts)) == 4, (stem, opts)
    ci = vs.index(ans)
    assert opts[ci] == fmt(ans)
    ITEMS.append({
        "ref": f"qxp-{len(ITEMS) + 1:03d}",
        "domain": "quantitative",
        "qtype": qtype,
        "topic": "אחוזים",
        "subtopic": sub,
        "stem": stem,
        "options": opts,
        "correct_index": ci,
        "difficulty": d,
        "target_seconds": secs,
        "explanation": expl,
        "solution": sol,
        "tags": tags,
    })


