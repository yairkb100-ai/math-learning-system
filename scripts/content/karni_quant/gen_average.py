def add(sub, stem, ans, ds, expl, method, diff, secs, qtype="word-problem",
        tags=("average",), unit=""):
    ans = F(ans)
    ds = [(F(v), w) for v, w in ds]
    assert len(ds) == 3, sub
    allv = [ans] + [v for v, _ in ds]
    assert len(set(allv)) == 4, f"{sub}: options not distinct {allv}"
    for v, _ in ds:
        assert v != ans, f"{sub}: distractor equals answer"
    pairs = sorted([(ans, None)] + ds, key=lambda p: p[0])
    options = [fm(v) + unit for v, _ in pairs]
    assert len(set(options)) == 4
    ci = [i for i, (v, w) in enumerate(pairs) if w is None][0]
    assert F(pairs[ci][0]) == ans
    parts = [f"המסיח {fm(v) + unit} {w}" for v, w in pairs if w is not None]
    sol = f"{method} {parts[0]}, ו{parts[1]}. {parts[2]}."
    fix = lambda t: t.replace("×", chr(92) + "times").replace("…", chr(92) + "ldots ")
    stem, expl, sol = fix(stem), fix(expl), fix(sol)
    ITEMS.append({
        "ref": "",
        "domain": "quantitative",
        "qtype": qtype,
        "topic": "ממוצע",
        "subtopic": sub,
        "stem": stem,
        "options": options,
        "correct_index": ci,
        "difficulty": diff,
        "target_seconds": secs,
        "explanation": expl,
        "solution": sol,
        "tags": list(tags),
    })


