add("מילוי עם דליפה", f"ברז ממלא מיכל בקצב של {fill} ליטרים בדקה, אבל דרך חור במיכל דולפים ממנו {leak} ליטרים בדקה. תוך כמה דקות יתמלא מיכל ריק של {tank} ליטרים?",
    MIN, ans, [F(tank, fill), F(tank, leak), F(tank, fill + leak)], 3, 50,
    f"קצב המילוי נטו הוא ${fill}-{leak}={fill-leak}$ ליטרים בדקה, ולכן המיכל יתמלא תוך ${tank}:{fill-leak}={n(ans)}$ דקות.",
    f"הדליפה פועלת נגד המילוי, ולכן מחסרים אותה מהקצב לפני החילוק. מי שהתעלם מהדליפה קיבל {tank//fill}, מי שחיבר את הדליפה לקצב קיבל {tank//(fill+leak)}, ומי שחילק בדליפה בלבד קיבל {tank//leak}.",
    ["fill-and-drain", "net-rate"])

# Dan and Rani
dan, rani, dal = 12, 6, 6
rem = 1 - F(dal, dan)
ans = rem / (F(1, dan) + F(1, rani))
add("אחד מתחיל ושניהם מסיימים", f"דן צובע דירה לבדו ב-{dan} ימים, ורני צובע אותה לבדו ב-{rani} ימים. דן התחיל לבד ועבד {dal} ימים, ואז הצטרף אליו רני. כמה ימים עבדו שניהם יחד עד סיום?",
    DAY, ans, [3, 6, dal + ans], 3, 60,
    f"דן עשה בשישה ימים ${T(F(dal,dan))}$ מהעבודה. שניהם יחד עושים ${T(F(1,dan))}+{T(F(1,rani))}={T(F(1,dan)+F(1,rani))}$ ביום, ולכן החצי הנותר ייקח ${T(rem)}:{T(F(1,dan)+F(1,rani))}={n(ans)}$ ימים.",
    f"מחשבים מה נותר אחרי השלב הראשון ואז מחלקים בקצב המשותף. מי שהניח שרני בלבד מסיימת את החצי הנותר קיבל 3 ימים, ומי שהניח שדן בלבד ממשיך קיבל 6. מי שכלל גם את ששת הימים הראשונים בזמן המשותף קיבל {n(dal+ans)}, אך השאלה היא על הימים של עבודה משותפת.",
    ["joined-midway", "combined-work"])

# add workers midway
w0, d0, after, extra = 6, 15, 5, 4
total_wd = w0 * d0
rem_wd = total_wd - w0 * after
ans = F(rem_wd, w0 + extra)
add("תוספת פועלים באמצע", f"{w0} פועלים אמורים לסיים עבודה ב-{d0} ימים. אחרי {after} ימים הצטרפו אליהם עוד {extra} פועלים באותו קצב. כמה ימים נוספים יידרשו לסיום?",
    DAY, ans, [d0 - after, extra, d0 - w0], 3, 60,
    f"בסך הכול ${w0} \\times {d0}={total_wd}$ ימי-פועל. אחרי {after} ימים בוצעו ${w0} \\times {after}={w0*after}$, ונותרו ${total_wd-w0*after}$. עם {w0+extra} פועלים זה ${rem_wd}:{w0+extra}={n(ans)}$ ימים.",
    f"מחשבים את סך העבודה בימי-פועל, מפחיתים את מה שנעשה, ומחלקים במספר הפועלים החדש. מי שהתעלם מהתוספת השאיר {d0-after} ימים, כלומר את הזמן שנותר בתכנון המקורי. התשובה {extra} היא מספר הפועלים שנוספו, והתשובה {d0-w0} מתקבלת מחיסור ${d0}-{w0}$; שתיהן נבנו ממספרי השאלה בלי קשר לכמות העבודה.",
    ["joined-midway", "worker-count"])

