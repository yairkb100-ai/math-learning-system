def n(x):
    """plain number text: integers with thousands comma, otherwise at most 2 decimals."""
    x = F(x)
    if x.denominator == 1:
        return f"{x.numerator:,}"
    assert (x * 100).denominator == 1, f"ugly number {x}"
    return ("%.2f" % float(x)).rstrip("0").rstrip(".")


def fmt(x, u):
    x = F(x)
    if "{}" in u[0]:
        return u[0].format(n(x))
    if x == 1:
        return u[0]
    return f"{n(x)} {u[1]}"


def T(x):
    """LaTeX for a number inside $...$"""
    x = F(x)
    if x.denominator == 1:
        return str(x.numerator)
    return r"\frac{%d}{%d}" % (x.numerator, x.denominator)


def add(sub, stem, unit, ans, dists, diff, ts, expl, sol, tags):
    ans = F(ans)
    dists = [F(d) for d in dists]
    assert len(dists) == 3, stem
    vals = dists + [ans]
    assert len(set(vals)) == 4, ("duplicate values", stem, vals)
    assert all(v > 0 for v in vals), stem
    for d in dists:  # every distractor value must be named in the solution
        assert n(d) in sol, ("distractor not named in solution", n(d), stem)
    assert n(ans) in expl or n(ans) in sol, ("answer missing in text", stem)
    assert expl != sol
    order = sorted(vals)
    opts = [fmt(v, unit) for v in order]
    assert len(set(opts)) == 4
    idx = order.index(ans)
    assert opts[idx] == fmt(ans, unit)
    assert "$" not in "".join(opts)
    ITEMS.append(dict(ref="", domain="quantitative", qtype="word-problem", topic="הספק",
                      subtopic=sub, stem=stem, options=opts, correct_index=idx,
                      difficulty=diff, target_seconds=ts, explanation=expl,
                      solution=sol, tags=tags))


