    "מחסרים את קצב הניקוז מקצב הברז ומחלקים רק את החלק שנותר למלא, כלומר חצי. מי שהתעלם מהניקוז קיבל 3 שעות, כי חצי בריכה ממולאת בברז לבדו. מי שחישב מבריכה ריקה, $1:\\frac{1}{12}$, קיבל 12. מי שחיבר את 3 ל-6 קיבל 9, אך החיבור הזה אינו מייצג שום שלב בבעיה.",
