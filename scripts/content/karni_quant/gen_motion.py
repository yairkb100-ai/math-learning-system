def n(x):
    """Format a Fraction as a plain decimal (asserts it is a finite decimal)."""
    x = F(x)
    if x.denominator == 1:
        return str(x.numerator)
    d = x.denominator
    for p in (2, 5):
        while d % p == 0:
            d //= p
    assert d == 1, f"not a finite decimal: {x}"
    s = f"{float(x):.6f}".rstrip("0").rstrip(".")
    return s


def clock(m):
    m = int(m)
    return f"{m // 60}:{m % 60:02d}"


def hm(h, mi=0):
    return F(h * 60 + mi)


def M(s):
    return "$" + s + "$"


def add(sub, diff, secs, stem, ans, wrongs, unit, expl, sol, tags):
    """ans: Fraction (or minutes-since-midnight when unit is None => clock)."""
    ans = F(ans)
    wrongs = [F(w) for w in wrongs]
    assert len(wrongs) == 3, (sub, wrongs)
    assert all(w != ans for w in wrongs), ("distractor equals answer", sub)
    assert len(set(wrongs + [ans])) == 4, ("duplicate options", sub)
    vals = sorted(wrongs + [ans])
    if unit is None:
        opts = [clock(v) for v in vals]
    else:
        opts = [("שעה" if (unit == "שעות" and v == 1) else f"{n(v)} {unit}") for v in vals]
    assert len(set(opts)) == 4, ("duplicate option text", sub)
    ITEMS.append({
        "ref": f"qxv-{len(ITEMS) + 1:03d}",
        "domain": "quantitative",
        "qtype": "word-problem",
        "topic": "תנועה",
        "subtopic": sub,
        "stem": stem,
        "options": opts,
        "correct_index": vals.index(ans),
        "difficulty": diff,
        "target_seconds": secs,
        "explanation": expl,
        "solution": sol,
        "tags": tags,
    })


