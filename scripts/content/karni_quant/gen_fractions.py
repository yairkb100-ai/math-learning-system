ITEMS = []


def mk(sub, qtype, diff, ts, stem, ans, mist, kind, expl, method, trap, tags):
    """mist: list of exactly 3 (value, description-after-'ממי ש')."""
    assert len(mist) == 3
    vals = [F(ans)] + [F(v) for v, _ in mist]
    assert len(set(vals)) == 4, (sub, vals)
    for v, _ in mist:
        assert F(v) != F(ans), (sub, v)
    order = sorted(range(4), key=lambda i: vals[i])
    opts = [kind.opt(vals[i]) for i in order]
    assert len(set(opts)) == 4, (sub, opts)
    ci = order.index(0)
    assert vals[order[ci]] == F(ans)
    parts = [f"המסיח {kind.tex(v)} מתקבל ממי ש{d}" for v, d in mist]
    mist_sentence = parts[0] + ", " + "ו" + parts[1].replace("המסיח", "המסיח", 1) + ", ו" + parts[2] + "."
    ITEMS.append({
        "ref": f"qxf-{len(ITEMS) + 1:03d}",
        "domain": "quantitative",
        "qtype": qtype,
        "topic": "שברים ועשרוניים",
        "subtopic": sub,
        "stem": stem,
        "options": opts,
        "correct_index": ci,
        "difficulty": diff,
        "target_seconds": ts,
        "explanation": expl,
        "solution": f"{method} {trap} {mist_sentence}",
        "tags": tags,
    })


