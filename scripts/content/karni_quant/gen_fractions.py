# ---------- formatting kinds ----------
def dec_str(x):
    x = F(x)
    for k in range(0, 9):
        y = x * 10 ** k
        if y.denominator == 1:
            n = int(y)
            if k == 0:
                return str(n)
            s = str(n).rjust(k + 1, "0")
            return s[:-k] + "." + s[-k:]
    raise ValueError(f"non-terminating {x}")


def frac_tex(x):
    x = F(x)
    return str(x.numerator) if x.denominator == 1 else r"\frac{%d}{%d}" % (x.numerator, x.denominator)


def mixed_parts(x):
    x = F(x)
    w = x.numerator // x.denominator
    r = x - w
    return w, r


def mixed_tex(x):
    w, r = mixed_parts(x)
    return f"{w}" + frac_tex(r)


class Frac:
    """options like 3/4 (all four must be non-integers)"""
    def opt(self, x):
        x = F(x)
        assert x.denominator != 1, x
        return f"{x.numerator}/{x.denominator}"

    def tex(self, x):
        return "$" + frac_tex(x) + "$"


class RawFrac:
    """options written as unreduced a/b strings; values passed as (a, b) tuples via F(a, b)
    but displayed with the given denominator."""
    def __init__(self, den):
        self.den = den

    def opt(self, x):
        y = F(x) * self.den
        assert y.denominator == 1, (x, self.den)
        return f"{int(y)}/{self.den}"

    def tex(self, x):
        y = F(x) * self.den
        return "$" + r"\frac{%d}{%d}" % (int(y), self.den) + "$"


class Mixed:
    def opt(self, x):
        x = F(x)
        w, r = mixed_parts(x)
        assert w >= 1 and r != 0, x
        return f"{w} {r.numerator}/{r.denominator}"

    def tex(self, x):
        return "$" + mixed_tex(x) + "$"


class Dec:
    def opt(self, x):
        return dec_str(x)

    def tex(self, x):
        return "$" + dec_str(x) + "$"


class Pct:
    def opt(self, x):
        return dec_str(F(x) * 100) + "%"

    def tex(self, x):
        return "$" + dec_str(F(x) * 100) + r"\%$"


FR, MX, DEC, PCT = Frac(), Mixed(), Dec(), Pct()


def T(x):
    return "$" + frac_tex(x) + "$"


def TM(x):
    return "$" + mixed_tex(x) + "$"


def TD(x):
    return "$" + dec_str(x) + "$"


